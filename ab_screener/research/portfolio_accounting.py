PORTFOLIO_MODEL_VERSION = "research-portfolio-v2.1.0"
_MICRO_PER_YUAN = Decimal(1000000)
_FEN_PER_AMOUNT_K_YUAN = Decimal(100000)


class PortfolioAccountingError(RuntimeError):
    """Fail-closed input or accounting error."""


@dataclass(frozen=True)
class PortfolioPolicy:
    version: str = PORTFOLIO_MODEL_VERSION
    initial_cash_fen: int = 100_000_000
    single_name_weight_bps: int = 1_000
    gross_exposure_bps: int = 8_000
    minimum_cash_bps: int = 1_000
    daily_new_buy_bps: int = 2_000
    participation_bps: int = 500
    cost_multiplier_bps: int = 10_000
    stock_lot_size: int = 100
    volume_unit: str = "hand"

    def __post_init__(self) -> None:
        if self.version != PORTFOLIO_MODEL_VERSION:
            raise PortfolioAccountingError(f"未知组合模型版本: {self.version}")
        if self.initial_cash_fen <= 0:
            raise PortfolioAccountingError("initial_cash_fen 必须为正整数")
        for name in (
            "single_name_weight_bps",
            "gross_exposure_bps",
            "minimum_cash_bps",
            "daily_new_buy_bps",
            "participation_bps",
            "cost_multiplier_bps",
        ):
            value = getattr(self, name)
            upper = 50_000 if name == "cost_multiplier_bps" else 10_000
            if not isinstance(value, int) or not 0 <= value <= upper:
                raise PortfolioAccountingError(f"{name} 必须为 0..{upper} 的整数")
        if self.cost_multiplier_bps <= 0:
            raise PortfolioAccountingError("cost_multiplier_bps 必须大于 0")
        if self.single_name_weight_bps > self.gross_exposure_bps:
            raise PortfolioAccountingError("单标的权重不能超过总仓位上限")
        if self.gross_exposure_bps + self.minimum_cash_bps > 10_000:
            raise PortfolioAccountingError("总仓位与最低现金之和不能超过 100%")
        if self.stock_lot_size <= 0:
            raise PortfolioAccountingError("stock_lot_size 必须为正整数")
        if self.volume_unit not in {"hand", "share"}:
            raise PortfolioAccountingError("volume_unit 只能是 hand 或 share")

    def fingerprint(self) -> str:
        payload = {key: getattr(self, key) for key in self.__dataclass_fields__}
        payload["execution_model_version"] = EXECUTION_MODEL_VERSION
        payload["fee_version"] = FEE_VERSION
        return hashlib.sha256(
            json.dumps(payload, sort_keys=True, ensure_ascii=False).encode("utf-8")
        ).hexdigest()[:16]


@dataclass(frozen=True)
class PreparedPortfolioMarket:
    """Immutable-by-contract market index reused across a parameter grid."""

    bars: Mapping[tuple[str, str], Quote]
    calendar: tuple[str, ...]
    policy_fingerprint: str


@dataclass
class _Position:
    ts_code: str
    qty: int
    cost_basis_fen: int
    entry_date: str
    planned_exit_date: str
    planned_exit_price_micro: int
    exit_type: str
    last_close_micro: int
    realized_pnl_fen: int = 0


def load_portfolio_policy(path: str | Path) -> PortfolioPolicy:
    payload = yaml.safe_load(Path(path).read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise PortfolioAccountingError("组合配置必须是对象")
    return PortfolioPolicy(**payload)


def resolved_stock_rules(
    codes: list[str],
    policy: PortfolioPolicy,
) -> dict[str, InstrumentRule]:
    """Resolve an explicit rule object per instrument; non-stock inputs fail."""
    result: dict[str, InstrumentRule] = {}
    for code in sorted(set(codes)):
        if not is_a_share_stock(code):
            raise PortfolioAccountingError(f"非 A 股股票不能进入首版组合研究: {code}")
        base = default_rule(code, "STOCK")
        result[code] = InstrumentRule(
            ts_code=code,
            inst_type="STOCK",
            commission_bps=base.commission_bps,
            min_commission_fen=base.min_commission_fen,
            sell_tax_bps=base.sell_tax_bps,
            other_fee_bps=base.other_fee_bps,
            slippage_bps=base.slippage_bps,
            lot_size=policy.stock_lot_size,
        )
    return result


def prepare_portfolio_market(
    market_data: pd.DataFrame,
    policy: PortfolioPolicy,
) -> PreparedPortfolioMarket:
    """Normalize OHLCV once so every grid combination sees identical quotes."""
    bars, calendar = _build_market_index(market_data, policy)
    return PreparedPortfolioMarket(
        bars=bars,
        calendar=tuple(calendar),
        policy_fingerprint=policy.fingerprint(),
    )


def simulate_portfolio(
    trades: list[dict[str, Any]],
    market_data: pd.DataFrame | PreparedPortfolioMarket,
    *,
    policy: PortfolioPolicy,
    rules: Mapping[str, InstrumentRule] | None = None,
    cancellation_checkpoint: Callable[[], None] | None = None,
    progress_callback: Callable[[int, int], None] | None = None,
) -> dict[str, Any]:
    """Run exact shared-account simulation over frozen candidate trades."""
    normalized = _normalize_trades(trades)
    if not normalized:
        return _empty_result(policy)
    if isinstance(market_data, PreparedPortfolioMarket):
        if market_data.policy_fingerprint != policy.fingerprint():
            raise PortfolioAccountingError("预处理行情与组合配置版本不一致")
        bars = market_data.bars
        calendar = list(market_data.calendar)
    else:
        prepared = prepare_portfolio_market(market_data, policy)
        bars = prepared.bars
        calendar = list(prepared.calendar)
    codes = sorted({row["ts_code"] for row in normalized})
    rule_map = dict(rules or resolved_stock_rules(codes, policy))
    missing_rules = sorted(set(codes) - set(rule_map))
    if missing_rules:
        raise PortfolioAccountingError(f"缺少 instrument 规则: {missing_rules[:5]}")

    entries: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in normalized:
        entries[row["entry_date"]].append(row)
    for dated_entries in entries.values():
        dated_entries.sort(key=lambda item: (item["signal_date"], item["ts_code"]))

    first_date = min(entries)
    relevant_calendar = [day for day in calendar if day >= first_date]
    if not relevant_calendar:
        raise PortfolioAccountingError("组合窗口内没有交易日")

    cash_fen = policy.initial_cash_fen
    positions: dict[str, _Position] = {}
    events: list[dict[str, Any]] = []
    equity_curve: list[dict[str, Any]] = []
    realized_pnls: list[int] = []
    fee_totals: Counter[str] = Counter()
    rejection_counts: Counter[str] = Counter()
    peak_fen = policy.initial_cash_fen
    min_cash_fen = cash_fen
    max_gross_bps = 0

    calendar_count = len(relevant_calendar)
    for calendar_index, trade_date in enumerate(relevant_calendar, start=1):
        if cancellation_checkpoint is not None:
            cancellation_checkpoint()
        if progress_callback is not None and (
            calendar_index == 1
            or calendar_index == calendar_count
            or calendar_index % 20 == 0
        ):
            progress_callback(calendar_index, calendar_count)
        day_start_equity = _equity_at_price(cash_fen, positions, bars, trade_date, price_field="open_micro")
        cash_fen = _process_exits(
            trade_date,
            cash_fen,
            positions,
            bars,
            rule_map,
            policy,
            events,
            realized_pnls,
            fee_totals,
            rejection_counts,
        )
        day_spend_fen = 0
        daily_entries: list[dict[str, Any]] = []
        for row in entries.get(trade_date, []):
            code = row["ts_code"]
            if code in positions:
                rejection_counts["DUPLICATE_ACTIVE_POSITION"] += 1
                events.append(
                    {
                        "event": "ENTRY_REJECTED",
                        "ts_code": code,
                        "trade_date": trade_date,
                        "filled": False,
                        "qty": 0,
                        "reason": "DUPLICATE_ACTIVE_POSITION",
                    }
                )
                continue
            daily_entries.append(row)
        for index, row in enumerate(daily_entries):
            code = row["ts_code"]
            bar = _require_bar(bars, code, trade_date)
            equity_open = _equity_at_price(cash_fen, positions, bars, trade_date, price_field="open_micro")
            gross_open = _market_value(positions, bars, trade_date, price_field="open_micro")
            reserve_fen = equity_open * policy.minimum_cash_bps // 10_000
            gross_room = max(0, equity_open * policy.gross_exposure_bps // 10_000 - gross_open)
            cash_room = max(0, cash_fen - reserve_fen)
            daily_room = max(
                0,
                day_start_equity * policy.daily_new_buy_bps // 10_000 - day_spend_fen,
            )
            available = min(gross_room, cash_room, daily_room)
            remaining = max(1, len(daily_entries) - index)
            single_cap = equity_open * policy.single_name_weight_bps // 10_000
            budget_fen = min(single_cap, available // remaining)
            fill = _buy_fill(code, trade_date, bar, rule_map[code], policy, budget_fen)
            if not fill.filled:
                rejection_counts[fill.reason] += 1
                events.append(_event_payload(fill, "ENTRY_REJECTED"))
                continue
            if fill.cash_delta_fen >= 0 or cash_fen + fill.cash_delta_fen < 0:
                raise PortfolioAccountingError("买入现金变化非法")
            cash_fen += fill.cash_delta_fen
            day_spend_fen += -fill.cash_delta_fen
            positions[code] = _Position(
                ts_code=code,
                qty=fill.qty,
                cost_basis_fen=-fill.cash_delta_fen,
                entry_date=trade_date,
                planned_exit_date=row["exit_date"],
                planned_exit_price_micro=row["exit_price_micro"],
                exit_type=row["exit_type"],
                last_close_micro=bar.close_micro,
            )
            _add_fees(fee_totals, fill)
            events.append(_event_payload(fill, "ENTRY_FILLED"))

        market_value_fen = _mark_positions(positions, bars, trade_date, events)
        equity_fen = cash_fen + market_value_fen
        if equity_fen < 0 or cash_fen < 0:
            raise PortfolioAccountingError("组合出现负现金或负权益")
        peak_fen = max(peak_fen, equity_fen)
        drawdown = Decimal(peak_fen - equity_fen) / Decimal(peak_fen)
        gross_bps = market_value_fen * 10_000 // equity_fen if equity_fen > 0 else 10_000
        max_gross_bps = max(max_gross_bps, gross_bps)
        min_cash_fen = min(min_cash_fen, cash_fen)
        equity_curve.append(
            {
                "trade_date": trade_date,
                "cash_fen": cash_fen,
                "market_value_fen": market_value_fen,
                "equity_fen": equity_fen,
                "gross_exposure_bps": gross_bps,
                "drawdown": _decimal_float(drawdown),
                "position_count": len(positions),
            }
        )

    final_equity = equity_curve[-1]["equity_fen"]
    positives = [value for value in realized_pnls if value > 0]
    negatives = [value for value in realized_pnls if value < 0]
    profit_factor = (
        Decimal(sum(positives)) / Decimal(abs(sum(negatives))) if positives and negatives else None
    )
    daily_returns = _daily_returns(equity_curve, policy.initial_cash_fen)
    result = {
        "portfolio_model_version": policy.version,
        "portfolio_config_hash": policy.fingerprint(),
        "portfolio_execution_model_version": EXECUTION_MODEL_VERSION,
        "portfolio_fee_version": FEE_VERSION,
        "portfolio_status": "PASS" if not positions else "INCOMPLETE_OPEN_POSITIONS",
        "portfolio_initial_equity_fen": policy.initial_cash_fen,
        "portfolio_final_equity_fen": final_equity,
        "portfolio_net_pnl_fen": final_equity - policy.initial_cash_fen,
        "portfolio_total_return": _decimal_float(
            Decimal(final_equity) / Decimal(policy.initial_cash_fen) - Decimal(1)
        ),
        "portfolio_max_drawdown": max((float(row["drawdown"]) for row in equity_curve), default=0.0),
        "portfolio_realized_profit_factor": (
            _decimal_float(profit_factor) if profit_factor is not None else None
        ),
        "portfolio_realized_win_rate": (
            round(len(positives) / len(realized_pnls), 6) if realized_pnls else None
        ),
        "portfolio_n_entries": sum(e["event"] == "ENTRY_FILLED" for e in events),
        "portfolio_n_exits": len(realized_pnls),
        "portfolio_rejections": int(sum(rejection_counts.values())),
        "portfolio_rejection_reasons": dict(sorted(rejection_counts.items())),
        "portfolio_open_positions": len(positions),
        "portfolio_min_cash_fen": min_cash_fen,
        "portfolio_max_gross_exposure_bps": max_gross_bps,
        "portfolio_commission_fen": fee_totals["commission_fen"],
        "portfolio_stamp_tax_fen": fee_totals["stamp_tax_fen"],
        "portfolio_other_fee_fen": fee_totals["other_fee_fen"],
        "portfolio_slippage_fen": fee_totals["slippage_fen"],
        "portfolio_daily_returns": daily_returns,
        "portfolio_equity_sha256": _equity_hash(equity_curve),
        "equity_curve": equity_curve,
        "events": events,
    }
    return result


