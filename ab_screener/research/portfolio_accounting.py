"""Deterministic portfolio accounting for trusted Breakout research.

Candidate trades are generated by the frozen signal/exit engine.  This module
adds the account layer that the legacy trade-sequence summary lacked: shared
cash, overlapping positions, portfolio limits, exact integer fees and daily
mark-to-market equity.  It never changes a signal or chooses an exit parameter.
"""

