def _normalize_trades(trades: list[dict[str, Any]]) -> list[dict[str, Any]]:
    result: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str]] = set()
    for row in trades:
        if not row.get("cost", {}).get("filled"):
            continue
        code = str(row.get("ts_code") or "").strip().upper()
        signal_date = _date(row.get("date") or row.get("signal_date"))
        entry_date = _date(row.get("entry_date"))
        exit_date = _date(row.get("exit_date"))
        if not code or not signal_date or not entry_date or not exit_date:
            raise PortfolioAccountingError("成交候选缺少代码或信号/成交/退出日期")
        if not signal_date < entry_date < exit_date:
            raise PortfolioAccountingError(f"时间顺序非法: {code} {signal_date}/{entry_date}/{exit_date}")
        key = (code, entry_date, "")
        if key in seen:
            raise PortfolioAccountingError(f"重复成交候选: {key}")
        seen.add(key)
        exit_price_micro = _price_micro(row.get("exit_price"))
        if exit_price_micro <= 0:
            raise PortfolioAccountingError(f"退出参考价非法: {code} {exit_date}")
        result.append(
            {
                "ts_code": code,
                "signal_date": signal_date,
                "entry_date": entry_date,
                "exit_date": exit_date,
                "exit_price_micro": exit_price_micro,
                "exit_type": str(row.get("exit") or "time"),
            }
        )
    return sorted(result, key=lambda item: (item["entry_date"], item["ts_code"]))


def _build_market_index(
    market_data: pd.DataFrame,
    policy: PortfolioPolicy,
) -> tuple[dict[tuple[str, str], Quote], list[str]]:
    required = {"ts_code", "trade_date", "open", "high", "low", "close", "vol"}
    missing = required - set(market_data.columns)
    if missing:
        raise PortfolioAccountingError(f"行情缺字段: {sorted(missing)}")
    bars: dict[tuple[str, str], Quote] = {}
    for record in market_data.to_dict("records"):
        code = str(record["ts_code"]).strip().upper()
        trade_date = _date(record["trade_date"])
        key = (code, trade_date)
        if key in bars:
            raise PortfolioAccountingError(f"行情重复主键: {key}")
        volume = _int_decimal(record.get("vol"))
        if policy.volume_unit == "hand":
            volume *= 100
        amount_fen = _amount_fen(record.get("amount"))
        pre_close = record.get("pre_close")
        bars[key] = Quote(
            ts_code=code,
            trade_date=trade_date,
            open_micro=_price_micro(record.get("open")),
            high_micro=_price_micro(record.get("high")),
            low_micro=_price_micro(record.get("low")),
            close_micro=_price_micro(record.get("close")),
            vol=max(0, volume),
            amount_fen=max(0, amount_fen),
            pre_close_micro=(
                _price_micro(pre_close) if pre_close is not None and not pd.isna(pre_close) else None
            ),
            available_at=str(record.get("available_at") or ""),
        )
    calendar = sorted({date for _, date in bars})
    return bars, calendar


def _process_exits(
    trade_date: str,
    cash_fen: int,
    positions: dict[str, _Position],
    bars: Mapping[tuple[str, str], Quote],
    rules: Mapping[str, InstrumentRule],
    policy: PortfolioPolicy,
    events: list[dict[str, Any]],
    realized_pnls: list[int],
    fee_totals: Counter,
    rejection_counts: Counter[str],
) -> int:
    due = sorted(
        (position for position in positions.values() if position.planned_exit_date <= trade_date),
        key=lambda position: position.ts_code,
    )
    for position in due:
        actual = bars.get((position.ts_code, trade_date))
        if actual is None:
            rejection_counts["EXIT_NO_QUOTE"] += 1
            events.append(
                {
                    "event": "EXIT_RETRY",
                    "ts_code": position.ts_code,
                    "trade_date": trade_date,
                    "filled": False,
                    "qty": 0,
                    "reason": "NO_QUOTE",
                }
            )
            continue
        quote = actual
        if trade_date == position.planned_exit_date:
            quote = Quote(
                ts_code=actual.ts_code,
                trade_date=actual.trade_date,
                open_micro=position.planned_exit_price_micro,
                high_micro=actual.high_micro,
                low_micro=actual.low_micro,
                close_micro=actual.close_micro,
                vol=actual.vol,
                amount_fen=actual.amount_fen,
                pre_close_micro=actual.pre_close_micro,
                available_at=actual.available_at,
            )
        rule = rules[position.ts_code]
        fill = compute_fill(
            quote,
            FillRequest(
                ts_code=position.ts_code,
                side="SELL",
                trade_date=trade_date,
                input_hash=f"portfolio:{position.ts_code}:{position.entry_date}:{trade_date}:sell",
                participation_bps=policy.participation_bps,
                lot_size=rule.lot_size,
                position_qty=position.qty,
                requested_qty=position.qty,
                fees=portfolio_fee_params(rule, policy),
            ),
        )
        if not fill.filled:
            rejection_counts[f"EXIT_{fill.reason}"] += 1
            events.append(_event_payload(fill, "EXIT_RETRY"))
            continue
        old_qty = position.qty
        sold_cost = (
            position.cost_basis_fen if fill.qty == old_qty else position.cost_basis_fen * fill.qty // old_qty
        )
        position.qty -= fill.qty
        position.cost_basis_fen -= sold_cost
        cash_fen += fill.cash_delta_fen
        position.realized_pnl_fen += fill.cash_delta_fen - sold_cost
        _add_fees(fee_totals, fill)
        events.append({
            **_event_payload(fill, "EXIT_FILLED"),
            "entry_date": position.entry_date,
            "exit_type": position.exit_type,
            "allocated_cost_fen": sold_cost,
            "realized_pnl_fen": fill.cash_delta_fen - sold_cost,
        })
        if position.qty == 0:
            realized_pnls.append(position.realized_pnl_fen)
            del positions[position.ts_code]
    return cash_fen


def _buy_fill(
    code: str,
    trade_date: str,
    quote: Quote,
    rule: InstrumentRule,
    policy: PortfolioPolicy,
    budget_fen: int,
) -> FillV2:
    if budget_fen <= 0:
        return compute_fill(
            quote,
            FillRequest(
                ts_code=code,
                side="BUY",
                trade_date=trade_date,
                input_hash=f"portfolio:{code}:{trade_date}:zero-budget",
                participation_bps=policy.participation_bps,
                lot_size=rule.lot_size,
                cash_available_fen=0,
                requested_qty=rule.lot_size,
                fees=portfolio_fee_params(rule, policy),
            ),
        )
    if quote.open_micro <= 0:
        rough_qty = rule.lot_size
    else:
        buy_price = slipped_price_micro(
            quote.open_micro,
            "BUY",
            quote,
            _scaled_cost(rule.slippage_bps, policy.cost_multiplier_bps),
        )
        rough_qty = floor_to_lot(budget_fen * 10_000 // buy_price, rule.lot_size)
    return compute_fill(
        quote,
        FillRequest(
            ts_code=code,
            side="BUY",
            trade_date=trade_date,
            input_hash=f"portfolio:{code}:{trade_date}:buy",
            participation_bps=policy.participation_bps,
            lot_size=rule.lot_size,
            cash_available_fen=budget_fen,
            requested_qty=max(rough_qty, rule.lot_size),
            fees=portfolio_fee_params(rule, policy),
        ),
    )


def portfolio_fee_params(rule: InstrumentRule, policy: PortfolioPolicy) -> FeeParams:
    """Resolve the exact versioned fee/slippage assumptions for one policy."""
    return FeeParams(
        commission_bps=_scaled_cost(rule.commission_bps, policy.cost_multiplier_bps),
        commission_min_fen=_scaled_cost(rule.min_commission_fen, policy.cost_multiplier_bps),
        stamp_tax_bps=_scaled_cost(rule.sell_tax_bps, policy.cost_multiplier_bps),
        other_fee_bps=_scaled_cost(rule.other_fee_bps, policy.cost_multiplier_bps),
        slippage_bps=_scaled_cost(rule.slippage_bps, policy.cost_multiplier_bps),
    )


def _scaled_cost(value: int, multiplier_bps: int) -> int:
    return (int(value) * int(multiplier_bps) + 5_000) // 10_000


def _event_payload(fill: FillV2, event: str) -> dict[str, Any]:
    return {"event": event, **fill.to_dict()}


def _add_fees(totals: Counter, fill: FillV2) -> None:
    for key, value in fill.fees.to_dict().items():
        totals[key] += value


def _market_value(
    positions: Mapping[str, _Position],
    bars: Mapping[tuple[str, str], Quote],
    trade_date: str,
    *,
    price_field: str,
) -> int:
    total = 0
    for code, position in positions.items():
        quote = bars.get((code, trade_date))
        price_micro = int(getattr(quote, price_field)) if quote is not None else position.last_close_micro
        total += price_micro * position.qty // 10_000
    return total


def _equity_at_price(
    cash_fen: int,
    positions: Mapping[str, _Position],
    bars: Mapping[tuple[str, str], Quote],
    trade_date: str,
    *,
    price_field: str,
) -> int:
    return cash_fen + _market_value(positions, bars, trade_date, price_field=price_field)


def _mark_positions(
    positions: Mapping[str, _Position],
    bars: Mapping[tuple[str, str], Quote],
    trade_date: str,
    events: list[dict[str, Any]],
) -> int:
    total = 0
    for code, position in positions.items():
        quote = bars.get((code, trade_date))
        if quote is not None:
            position.last_close_micro = quote.close_micro
        else:
            events.append(
                {
                    "event": "MARK_CARRY_FORWARD",
                    "ts_code": code,
                    "trade_date": trade_date,
                    "price_micro": position.last_close_micro,
                    "reason": "NO_QUOTE",
                }
            )
        total += position.last_close_micro * position.qty // 10_000
    return total


def _require_bar(
    bars: Mapping[tuple[str, str], Quote],
    code: str,
    trade_date: str,
) -> Quote:
    quote = bars.get((code, trade_date))
    if quote is None:
        raise PortfolioAccountingError(f"持仓或成交缺少当日估值行情: {code} {trade_date}")
    return quote


def _daily_returns(equity_curve: list[dict[str, Any]], initial_equity_fen: int) -> list[float]:
    result: list[float] = []
    previous = initial_equity_fen
    for row in equity_curve:
        equity = int(row["equity_fen"])
        if previous > 0:
            result.append(_decimal_float(Decimal(equity) / Decimal(previous) - Decimal(1)))
        previous = equity
    return result


def _equity_hash(equity_curve: list[dict[str, Any]]) -> str:
    payload = json.dumps(equity_curve, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _date(value: Any) -> str:
    digits = "".join(ch for ch in str(value or "") if ch.isdigit())
    return digits[:8] if len(digits) >= 8 else ""


def _price_micro(value: Any) -> int:
    if value is None or pd.isna(value):
        return 0
    return int((Decimal(str(value)) * _MICRO_PER_YUAN).quantize(Decimal(1), rounding=ROUND_HALF_UP))


def _int_decimal(value: Any) -> int:
    if value is None or pd.isna(value):
        return 0
    return int(Decimal(str(value)))


def _amount_fen(value: Any) -> int:
    if value is None or pd.isna(value):
        return 0
    return int((Decimal(str(value)) * _FEN_PER_AMOUNT_K_YUAN).quantize(Decimal(1), rounding=ROUND_HALF_UP))


def _decimal_float(value: Decimal) -> float:
    return float(value.quantize(Decimal("0.00000001"), rounding=ROUND_HALF_UP))


